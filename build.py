"""Build self-contained classic bundles. Python standard library; no CDN or npm build.
Editable ES-module sources are retained. Run tests before distributing.
"""
from pathlib import Path
import re,json
ROOT=Path(__file__).resolve().parent
JS=ROOT/'js'
VERSION=json.loads((ROOT/'package.json').read_text())['version']
# Stamp release identity without touching historical/component identifiers.
for name in ['index.html','METHODS.html','GLARE.html','GLARE_GUIDE.html','START_HERE.html']:
    p=ROOT/name
    text=p.read_text()
    text=re.sub(r'(<span data-workspace-version>)[^<]*(</span>)',lambda m:m[1]+VERSION+m[2],text)
    text=re.sub(r'(<title>[^<]*?)(?:0\.\d+(?:\.\d+)?)([^<]*</title>)',lambda m:m[1]+VERSION+m[2],text)
    text=re.sub(r'([?&]v=)0\.\d+(?:\.\d+)?',lambda m:m[1]+VERSION,text)
    p.write_text(text)
for name in ['app.js','glareui.js']:
    p=JS/name
    p.write_text(re.sub(r'([?&]v=)0\.\d+(?:\.\d+)?',lambda m:m[1]+VERSION,p.read_text()))
p=JS/'worker.js'
p.write_text(re.sub(r"const VERSION='[^']+';", "const VERSION='"+VERSION+"';",p.read_text()))
(ROOT/'release.json').write_text(json.dumps({'name':'VisionSim HDR Web','version':VERSION},indent=2)+'\n')
(JS/'nativeassets.js').write_text('export const NATIVE_RUNNER='+json.dumps((ROOT/'native/run_glare.py').read_text())+';\n')
def imports(source):
    return re.sub(r"import \{(.*?)\} from './(.*?)\.js';",lambda m:f"const {{{m[1]}}}={m[2].upper().replace(chr(45),chr(95))};",source)
def module(name):
    source=(JS/(name+'.js')).read_text()
    names=re.findall(r'export\s+(?:async\s+)?(?:function|const|class)\s+(\w+)',source)
    source=imports(source)
    source=re.sub(r'\bexport\s+','',source)
    return f"const {name.upper().replace(chr(45),chr(95))}=(()=>{{\n{source}\nreturn {{{','.join(names)}}};\n}})();\n"
ordered=['exr','geometry','resources','bracket','phone','heif','io','math','reproject','fov','falsecolor','cvd','guthdata','angles','selections','regionstats','regionbook','fieldloss','chroma','conditions','spherical','fieldmask','colorview','cropui','roiui','glare','zipstore','nativeassets','glaretask','glareui']
modules={name:module(name) for name in ordered}
header="/* Generated by build.py. Editable modules and notices are included. */\n'use strict';\n"
worker=imports((JS/'worker.js').read_text())
(JS/'engine.bundle.js').write_text(header+''.join(modules[n] for n in ordered if n not in ['zipstore','nativeassets','glareui'])+'\n(()=>{\n'+worker+'\n})();\n')
app=imports((JS/'app.js').read_text()).replace('import.meta.url','SCRIPT_URL')
(JS/'app.bundle.js').write_text(header+''.join(modules[n] for n in ['exr','geometry','resources','phone','heif','io','math','fov','falsecolor','guthdata','angles','selections','chroma','cropui','roiui','glare','zipstore','nativeassets','glaretask','glareui'])+'\n(()=>{const SCRIPT_URL=document.currentScript.src;\n'+app+'\n})();\n')
runner_modules=['exr','geometry','resources','phone','heif','io','math','guthdata','angles','glare']
runner=imports((JS/'glare-runner.js').read_text())
(JS/'glare-runner.bundle.js').write_text(header+''.join(modules[n] for n in runner_modules)+module('glare-engine')+'\n(()=>{\n'+runner+'\n})();\n')
print('Built local application, processing worker and real glare-worker bundles')
