"""Build self-contained classic bundles. Python standard library; no CDN or npm build.
Editable ES-module sources are retained. Run tests before distributing.
"""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parent
JS=ROOT/'js'
def imports(source):
    return re.sub(r"import \{(.*?)\} from './(.*?)\.js';",lambda m:f"const {{{m[1]}}}={m[2].upper()};",source)
def module(name):
    source=(JS/(name+'.js')).read_text()
    names=re.findall(r'export\s+(?:async\s+)?(?:function|const|class)\s+(\w+)',source)
    source=imports(source)
    source=re.sub(r'\bexport\s+','',source)
    return f"const {name.upper()}=(()=>{{\n{source}\nreturn {{{','.join(names)}}};\n}})();\n"
ordered=['exr','geometry','resources','bracket','phone','heif','io','math','reproject','fov','falsecolor','cvd','conditions','colorview']
modules={name:module(name) for name in ordered}
header="/* Generated by build.py. Editable modules and notices are included. */\n'use strict';\n"
worker=imports((JS/'worker.js').read_text())
(JS/'engine.bundle.js').write_text(header+''.join(modules.values())+'\n(()=>{\n'+worker+'\n})();\n')
app=imports((JS/'app.js').read_text()).replace('import.meta.url','SCRIPT_URL')
(JS/'app.bundle.js').write_text(header+''.join(modules[n] for n in ['exr','geometry','resources','phone','heif','io','fov','falsecolor'])+'\n(()=>{const SCRIPT_URL=document.currentScript.src;\n'+app+'\n})();\n')
print('Built local application and worker bundles')
